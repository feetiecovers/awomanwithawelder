export function getTrailerIcon(name: string) {
  const normalized = name.toLowerCase();
  if (normalized.includes("car hauler")) return CarHaulerIcon;
  if (normalized.includes("enclosed")) return EnclosedCargoIcon;
  if (normalized.includes("flatbed")) return FlatbedIcon;
  if (normalized.includes("tilt")) return TiltTrailerIcon;
  if (normalized.includes("boat")) return BoatTrailerIcon;
  if (normalized.includes("horse")) return HorseFloatIcon;
  if (normalized.includes("plant")) return PlantTrailerIcon;
  if (normalized.includes("tradesman")) return TradesmanTrailerIcon;
  if (normalized.includes("tipper")) return TipperTrailerIcon;
  if (normalized.includes("tag")) return TagTrailerIcon;
  return GenericTrailerIcon;
}
